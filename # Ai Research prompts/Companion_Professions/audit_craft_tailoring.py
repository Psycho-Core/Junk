def hygiene(text):
    lines = text.split("\n")
    problems = []
    if len([l for l in lines if len(l) > 100]) != 0:
        problems.append("line > 100 cols")
    if [l for l in lines if l != l.rstrip()] != []:
        problems.append("trailing whitespace")
    if not lines[0].startswith("BATTLE FOR AZEROTH 8.3.7 (BUILD 35662) - TAILORING"):
        problems.append("bad title")
    for i in range(1, 11):
        head = f"{i}." if i != 1 else "1. THE"
        if not any(l.startswith(f"{i}. ") for l in lines):
            problems.append(f"missing section {i}")
    if "unverified" not in text:
        problems.append("no unverified marker")
    return problems


